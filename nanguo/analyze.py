"""Analyse the user's copy of 孙燕姿《我不难过》 and write src/beatmap.js for the pixel MV.

    python3 analyze.py <song.mp3>

Writes build/bgm.wav (the song decoded, git-ignored) and src/beatmap.js with:
  - a constant beat grid (BPM + phase) fitted to the onsets,
  - low-band hits (kick) for things that land on the drum,
  - low / mid / high band envelopes at 30 fps for audio-reactive light,
  - the onset of every sung syllable, from Whisper word timestamps, so the subtitle highlight follows the
    singing. Only times are kept, never the words.
"""
import json
import os
import subprocess
import sys

import librosa
import numpy as np
from faster_whisper import WhisperModel

FPS = 30
FFMPEG = os.environ.get('FFMPEG', 'ffmpeg')
os.makedirs('build', exist_ok=True)
subprocess.run([FFMPEG, '-y', '-v', 'error', '-i', sys.argv[1], '-vn', '-ac', '2', '-ar', '44100',
                '-c:a', 'pcm_s16le', 'build/bgm.wav'], check=True)
y, sr = librosa.load('build/bgm.wav', sr=44100, mono=True)
dur = len(y) / sr

# ---- onset envelopes at 256-sample hops (5.8 ms)
hop = 256
S = np.abs(librosa.stft(y, n_fft=2048, hop_length=hop))
f = librosa.fft_frequencies(sr=sr, n_fft=2048)
t = librosa.frames_to_time(np.arange(S.shape[1]), sr=sr, hop_length=hop)


def flux(lo, hi):
    B = np.log1p(100 * S[(f >= lo) & (f < hi)])
    return np.concatenate([[0], np.maximum(0, np.diff(B, axis=1)).sum(0)])


lowf, midf = flux(30, 160), flux(160, 4000)
thr, kicks = np.percentile(lowf, 96), []
for i in range(1, len(lowf) - 1):
    if lowf[i] > thr and lowf[i] >= lowf[i - 1] and lowf[i] >= lowf[i + 1]:
        if not kicks or t[i] - kicks[-1][0] > 0.2:
            kicks.append((t[i], lowf[i]))
        elif lowf[i] > kicks[-1][1]:
            kicks[-1] = (t[i], lowf[i])

# ---- constant grid: start from librosa's tempo, then search nearby for the BPM and phase that put the
# most onset energy on the beats
env = lowf / lowf.max() + midf / midf.max()
tempo = float(np.atleast_1d(librosa.beat.beat_track(y=y, sr=sr, hop_length=512)[0])[0])
best = None
for bpm in np.arange(tempo - 4, tempo + 4, 0.02):
    beat = 60 / bpm
    grid = np.arange(0, t[-1], beat)
    for ph in np.arange(0, beat, 0.005):
        idx = np.clip(np.round((grid + ph) / (hop / sr)).astype(int), 0, len(env) - 1)
        sc = env[idx].mean()
        if best is None or sc > best[0]:
            best = (sc, bpm, ph)
_, bpm, phase = best

# ---- 30 fps band envelopes
H = sr // FPS
S2 = np.abs(librosa.stft(y, n_fft=4096, hop_length=H))
f2 = librosa.fft_frequencies(sr=sr, n_fft=4096)


def band(lo, hi):
    e = np.sqrt((S2[(f2 >= lo) & (f2 < hi)] ** 2).mean(0))
    return np.clip(e / np.percentile(e, 99), 0, 1.2)


# ---- sung syllables (Whisper; only the start time of each word is kept). Segments Whisper invents over the
# instrumental parts have low word confidence and are dropped.
a16 = librosa.resample(y, orig_sr=sr, target_sr=16000)
segs, _ = WhisperModel('medium', device='cpu', compute_type='int8').transcribe(
    a16, beam_size=5, language='zh', condition_on_previous_text=False, word_timestamps=True)
words = []
for s in segs:
    if not s.words:
        continue
    conf = float(np.mean([w.probability for w in s.words]))
    keep = conf >= 0.5
    print(f"{s.words[0].start:7.2f}-{s.words[-1].end:7.2f} conf={conf:.2f} words={len(s.words)} {'keep' if keep else 'DROP'}")
    if keep:
        words += [round(float(w.start), 2) for w in s.words]

bm = {
    'bpm': round(float(bpm), 3), 'beat': round(60 / float(bpm), 6), 'phase': round(float(phase), 4), 'duration': round(dur, 3),
    'kicks': [round(float(k), 3) for k, _ in kicks],
    'words': sorted(words),
    'env': {k: [round(float(x), 3) for x in band(*r)] for k, r in {'low': (30, 160), 'mid': (160, 2500), 'high': (2500, 16000)}.items()},
}
with open('src/beatmap.js', 'w') as fh:
    fh.write('// Generated by analyze.py from the background track. Do not edit by hand. No lyrics are stored.\nconst BEATMAP = ' + json.dumps(bm) + ';\n')
print(f"{bm['bpm']} BPM, first beat {bm['phase']} s, {dur:.2f} s, {len(bm['kicks'])} low hits, {len(words)} sung syllables")
